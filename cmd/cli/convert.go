// convert.go defines the "convert" subcommand.
//
// Unlike "generate" which reads from gots.yaml, "convert" takes a single
// Go file as input and writes TypeScript to stdout or an output file.
// No config file needed — uses sensible defaults with optional flag overrides.
//
// Usage:
//
//	gots convert path/to/types.go                         # stdout
//	gots convert path/to/types.go -o output.ts            # file
//	gots convert path/to/types.go --style enum            # override style
//	gots convert path/to/types.go --style const-object -o out.ts
package main

import (
	"fmt"
	"os"

	"github.com/khanakia/gots/pkg/config"
	"github.com/khanakia/gots/pkg/generator"
	"github.com/khanakia/gots/pkg/parser"
	"github.com/spf13/cobra"
)

// Flag variables for the convert command.
var (
	convertOutput          string
	convertStyle           string
	convertStructTag       string
	convertPointerHandling string
	convertEmptyInterface  string
	convertEmitValues      bool
)

// convertCmd is the "gots convert" subcommand.
//
// It provides a quick, config-free way to convert a single Go file to TypeScript.
// All settings have sensible defaults and can be overridden via flags.
var convertCmd = &cobra.Command{
	Use:   "convert <file.go>",
	Short: "Convert a single Go file to TypeScript",
	Long: `Convert a single Go source file to TypeScript without a config file.
Outputs to stdout by default, or to a file with --output.

Examples:
  gots convert pkg/constants/constants.go
  gots convert pkg/models/user.go -o frontend/src/types/user.ts
  gots convert types.go --style enum --emit-values`,
	Args: cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		inputFile := args[0]

		// Check the input file exists
		if _, err := os.Stat(inputFile); os.IsNotExist(err) {
			return fmt.Errorf("file not found: %s", inputFile)
		}

		// Build a config from flags with sensible defaults
		cfg := &config.Config{
			DefaultStyle:    convertStyle,
			EmitValuesArray: convertEmitValues,
			StructTag:       convertStructTag,
			PointerHandling: convertPointerHandling,
			EmptyInterface:  convertEmptyInterface,
			Header:          "// Code generated by gots. DO NOT EDIT.",
			TypeMap: map[string]string{
				"time.Time":       "string",
				"json.RawMessage": "unknown",
				"uuid.UUID":       "string",
			},
			Sources: []config.Source{
				{
					File:   inputFile,
					Output: convertOutput,
				},
			},
			Overrides: map[string]config.Override{},
		}

		// Parse the Go source file
		p := parser.New()
		if err := p.ParseFile(inputFile); err != nil {
			return fmt.Errorf("failed to parse %s: %w", inputFile, err)
		}

		gen := generator.New(cfg, p.Result())

		// If no output file specified, write to stdout
		if convertOutput == "" {
			output, err := gen.GenerateString(cfg.Sources[0])
			if err != nil {
				return fmt.Errorf("failed to generate: %w", err)
			}
			fmt.Print(output)
			return nil
		}

		// Otherwise write to file
		if err := gen.Generate(); err != nil {
			return fmt.Errorf("failed to generate: %w", err)
		}

		fmt.Fprintf(os.Stderr, "Written to %s\n", convertOutput)
		return nil
	},
}

func init() {
	convertCmd.Flags().StringVarP(&convertOutput, "output", "o", "", "Output .ts file path (default: stdout)")
	convertCmd.Flags().StringVarP(&convertStyle, "style", "s", "union", "Output style: union, enum, const-object")
	convertCmd.Flags().StringVar(&convertStructTag, "tag", "json", "Struct tag to read for field names")
	convertCmd.Flags().StringVar(&convertPointerHandling, "pointers", "optional", "Pointer handling: optional, nullable, both")
	convertCmd.Flags().StringVar(&convertEmptyInterface, "empty-interface", "unknown", "interface{}/any mapping: unknown, any")
	convertCmd.Flags().BoolVar(&convertEmitValues, "emit-values", false, "Emit companion values array for typed constants")
}
