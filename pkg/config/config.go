// Package config handles loading and validating the gots.yaml configuration file.
//
// The config file controls every aspect of code generation:
//   - Which Go files to parse (sources)
//   - How to convert each type (styles, overrides)
//   - How to map Go types to TypeScript types (type_map)
//   - Output file paths
//
// Config is loaded once at startup and passed through the pipeline:
//
//	config.Load("gots.yaml") → *Config → passed to parser and generator
package config

import (
	"fmt"
	"os"

	"gopkg.in/yaml.v3"
)

// Config is the top-level configuration loaded from gots.yaml.
//
// It contains global defaults (applied to all types unless overridden),
// a list of source files to parse, and per-type overrides.
type Config struct {
	// DefaultStyle is the output format for typed constants when no override exists.
	// Values: "union" (default), "enum", "const-object"
	DefaultStyle string `yaml:"default_style"`

	// EmitValuesArray controls whether to generate a companion values array
	// (e.g., export const MessageRoleValues = ["user", "assistant"] as const)
	EmitValuesArray bool `yaml:"emit_values_array"`

	// StructTag is which Go struct tag to read for field names.
	// Default: "json". Other common values: "yaml", "db", "toml"
	StructTag string `yaml:"struct_tag"`

	// PointerHandling decides how Go pointer fields map to TypeScript.
	// "optional" → field?: T
	// "nullable" → field: T | null
	// "both"     → field?: T | null
	PointerHandling string `yaml:"pointer_handling"`

	// EmptyInterface controls what Go's interface{}/any maps to in TypeScript.
	// "unknown" (default, safer) or "any"
	EmptyInterface string `yaml:"empty_interface"`

	// Header is prepended to every generated .ts file.
	// Default: "// Code generated by gots. DO NOT EDIT."
	Header string `yaml:"header"`

	// TypeMap maps Go types to TypeScript types.
	// Key is the full Go type (e.g., "time.Time", "uuid.UUID").
	// Value is the TypeScript type string (e.g., "string", "Date").
	// This is checked before the built-in primitive mapping.
	TypeMap map[string]string `yaml:"type_map"`

	// Sources lists the Go files to parse and where to write their TypeScript output.
	// Each source can have its own style, include/exclude filters, and output path.
	Sources []Source `yaml:"sources"`

	// Overrides provides per-type configuration that takes precedence over
	// source-level and global defaults. Keyed by Go type name.
	Overrides map[string]Override `yaml:"overrides"`
}

// Source defines a single Go source file to parse and its generation settings.
//
// The file path can be absolute or relative to where gots is invoked.
// This is one of the key advantages of YAML config — you can point to files
// anywhere on disk, including vendor directories or other repositories.
type Source struct {
	// File is the path to the Go source file. Supports absolute paths.
	// Example: "pkg/constants/constants.go" or "/home/user/project/types.go"
	File string `yaml:"file"`

	// Output is the path where the generated .ts file will be written.
	Output string `yaml:"output"`

	// Style overrides the global default_style for all types in this file.
	// Empty string means inherit from Config.DefaultStyle.
	Style string `yaml:"style"`

	// Include is a whitelist of type/const names to generate.
	// Supports * wildcard: "Message*", "*Status", "MessageRole"
	// Empty list means include everything.
	Include []string `yaml:"include"`

	// Exclude is a blacklist of type/const names to skip.
	// Supports * wildcard. Applied after Include.
	Exclude []string `yaml:"exclude"`

	// StructStyle controls struct output format: "interface" or "type".
	// Default: "interface"
	StructStyle string `yaml:"struct_style"`

	// EmbedStrategy controls how embedded structs are rendered.
	// "flatten"      → inline all fields
	// "extends"      → interface Post extends BaseModel
	// "intersection" → type Post = BaseModel & { ... }
	EmbedStrategy string `yaml:"embed_strategy"`
}

// Override provides per-type settings that override source-level and global defaults.
type Override struct {
	// Style overrides the output format for this specific type.
	Style string `yaml:"style"`

	// ValuesArray controls whether to emit a companion values array for this type.
	ValuesArray bool `yaml:"values_array"`

	// Name renames the type in TypeScript output.
	// Example: Go "FeedbackCategory" → TS "FeedbackType"
	Name string `yaml:"name"`

	// Fields provides per-field overrides for struct types.
	// Keyed by Go field name (not the json tag name).
	Fields map[string]FieldOverride `yaml:"fields"`
}

// FieldOverride provides per-field settings within a struct.
type FieldOverride struct {
	// Type overrides the TypeScript type for this field.
	// Example: "Date" for time.Time fields, "Record<string, unknown>" for json fields.
	Type string `yaml:"type"`

	// Skip excludes this field from the generated interface.
	Skip bool `yaml:"skip"`
}

// Load reads a YAML config file from disk, parses it, and applies defaults
// for any unset fields.
//
// The path can be absolute or relative. If the file doesn't exist or
// contains invalid YAML, an error is returned.
func Load(path string) (*Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading config file: %w", err)
	}

	cfg := &Config{}
	if err := yaml.Unmarshal(data, cfg); err != nil {
		return nil, fmt.Errorf("parsing config file: %w", err)
	}

	// Fill in sensible defaults for any unset fields
	applyDefaults(cfg)

	return cfg, nil
}

// applyDefaults fills in zero-value fields with sensible defaults.
// This runs after YAML parsing, so explicitly set values are preserved.
func applyDefaults(cfg *Config) {
	if cfg.DefaultStyle == "" {
		cfg.DefaultStyle = "union"
	}
	if cfg.StructTag == "" {
		cfg.StructTag = "json"
	}
	if cfg.PointerHandling == "" {
		cfg.PointerHandling = "optional"
	}
	if cfg.EmptyInterface == "" {
		cfg.EmptyInterface = "unknown"
	}
	if cfg.Header == "" {
		cfg.Header = "// Code generated by gots. DO NOT EDIT."
	}
	// Only set default type map if user didn't provide any.
	// If they set even one entry, we respect their map entirely.
	if cfg.TypeMap == nil {
		cfg.TypeMap = map[string]string{
			"time.Time":       "string",
			"json.RawMessage": "unknown",
		}
	}
}
